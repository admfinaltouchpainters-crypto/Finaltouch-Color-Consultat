#!/usr/bin/env python3
"""Build data/colors.js from the public color snapshots.

Usage:
  python3 tools/build_colors.py <bm_colors.json> <sw_raw.json>

bm_colors.json : Benjamin Moore catalog snapshot (github.com/josh-williams/undertone,
                 data/benjamin-moore/colors.json, retrieved from the manufacturer API 2026-11-05)
sw_raw.json    : Sherwin-Williams palette (github.com/Sonic12040/sw-color-tester,
                 src/data/palette.ts converted to JSON)

Output rows are compact arrays to keep the file small:
  BM: [code, name, hex, lrv, popular]
  SW: [code, name, hex, lrv, popular, interior, exterior, storeLocator, [coordinating codes]]
"""
import json, sys, datetime

def main(bm_path, sw_path, out_path="data/colors.js"):
    bm_raw = json.load(open(bm_path))
    bm, seen = [], set()
    for c in bm_raw:
        code = c["number"].strip()
        if code in seen:
            continue
        seen.add(code)
        bm.append([code, c["name"].strip(), c["hex"].upper().lstrip("#"),
                   round(float(c["lrv"]), 1) if c.get("lrv") is not None else None,
                   1 if c.get("is_best_selling") else 0])

    sw_raw = json.load(open(sw_path))
    by_id = {c["id"]: c["colorNumber"] for c in sw_raw}
    sw, seen = [], set()
    for c in sw_raw:
        if c.get("archived"):
            continue  # discontinued colors cannot be bought
        num = c["colorNumber"]
        if num in seen:
            continue
        seen.add(num)
        cols = c.get("brandedCollectionNames") or []
        popular = 1 if any(x.startswith("Top 50") for x in cols) else 0
        coord = []
        for k in ("coord1ColorId", "coord2ColorId", "whiteColorId"):
            v = (c.get("coordinatingColors") or {}).get(k)
            if v and v in by_id:
                coord.append("SW " + by_id[v])
        sw.append(["SW " + num, c["name"].strip(), c["hex"].upper().lstrip("#"),
                   round(float(c["lrv"]), 1), popular,
                   1 if c.get("isInterior") else 0, 1 if c.get("isExterior") else 0,
                   c.get("storeStripLocator") or "", coord])

    meta = {"built": datetime.date.today().isoformat(), "bmCount": len(bm), "swCount": len(sw)}
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/build_colors.py - do not edit by hand. */\n")
        f.write("window.FT_COLOR_META=" + json.dumps(meta) + ";\n")
        f.write("window.FT_BM=" + json.dumps(bm, separators=(",", ":"), ensure_ascii=False) + ";\n")
        f.write("window.FT_SW=" + json.dumps(sw, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(meta)

if __name__ == "__main__":
    main(*sys.argv[1:3])
